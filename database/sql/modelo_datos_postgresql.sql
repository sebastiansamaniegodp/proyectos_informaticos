DROP VIEW  IF EXISTS vw_stock_disponible CASCADE;
DROP TABLE IF EXISTS movimiento_stock CASCADE;
DROP TABLE IF EXISTS pedido_detalle   CASCADE;
DROP TABLE IF EXISTS pedido           CASCADE;
DROP TABLE IF EXISTS rollo_abierto    CASCADE;
DROP TABLE IF EXISTS stock            CASCADE;
DROP TABLE IF EXISTS producto         CASCADE;
DROP TABLE IF EXISTS familia          CASCADE;
DROP TABLE IF EXISTS cliente          CASCADE;
DROP TABLE IF EXISTS usuario          CASCADE;


--------------------------------------------------------------------------------
-- 1. FAMILIA
--    Las siete familias del listado del cliente.
--------------------------------------------------------------------------------
CREATE TABLE familia (
    id_familia   INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR(60)   NOT NULL,
    activo       CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_familia        PRIMARY KEY (id_familia),
    CONSTRAINT uq_familia_nombre UNIQUE (nombre),
    CONSTRAINT ck_familia_activo CHECK (activo IN ('S','N'))
);


--------------------------------------------------------------------------------
-- 2. PRODUCTO
--    Una fila por VARIANTE comercial, no por tipo de tejido (DD-01).
--
--    unidad_venta  = unidad de la pieza entera (DD-14)
--    fraccionable  = si ademas admite venta por metro cortado (DD-15)
--    precio_venta  = precio de UNA unidad de unidad_venta
--    precio_metro  = precio del metro cortado, solo si fraccionable = 'S'
--------------------------------------------------------------------------------
CREATE TABLE producto (
    id_producto       INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    codigo            VARCHAR(30)    NOT NULL,
    descripcion       VARCHAR(150)   NOT NULL,
    id_familia        INTEGER        NOT NULL,
    unidad_venta      VARCHAR(10)    NOT NULL,
    fraccionable      CHAR(1)        DEFAULT 'N' NOT NULL,
    metraje_rollo     INTEGER        NULL,
    altura_cm         INTEGER        NULL,
    abertura          VARCHAR(20)    NULL,
    calibre           VARCHAR(10)    NULL,
    precio_venta      BIGINT         NOT NULL,
    precio_metro      BIGINT         NULL,
    precio_mayorista  BIGINT         NULL,
    costo             BIGINT         NULL,
    activo            CHAR(1)        DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_producto          PRIMARY KEY (id_producto),
    CONSTRAINT uq_producto_codigo   UNIQUE (codigo),
    CONSTRAINT fk_producto_familia  FOREIGN KEY (id_familia)
        REFERENCES familia (id_familia),
    CONSTRAINT ck_producto_unidad   CHECK (unidad_venta IN ('ROLLO','METRO','KILO','UNIDAD')),
    CONSTRAINT ck_producto_fracc    CHECK (fraccionable IN ('S','N')),
    CONSTRAINT ck_producto_activo   CHECK (activo IN ('S','N')),
    CONSTRAINT ck_producto_precios  CHECK (precio_venta > 0),
    -- Un producto fraccionable necesita el metraje del rollo y el precio
    -- del metro; si no es fraccionable, ambos sobran (DD-15, RN-02).
    CONSTRAINT ck_producto_fracc_ok CHECK (
        (fraccionable = 'N')
        OR (fraccionable = 'S' AND metraje_rollo IS NOT NULL
                               AND precio_metro  IS NOT NULL)
    )
);

CREATE INDEX ix_producto_familia ON producto (id_familia);

COMMENT ON TABLE  producto IS 'Una fila por variante comercial (DD-01)';
COMMENT ON COLUMN producto.codigo IS 'Codigo unico: tipo-abertura-altura-presentacion, ej. HEX-12-150-50 (DD-01)';
COMMENT ON COLUMN producto.unidad_venta IS 'Unidad de la pieza entera: ROLLO, METRO, KILO o UNIDAD (DD-14)';
COMMENT ON COLUMN producto.fraccionable IS 'S = admite corte por metro; N = solo pieza entera (DD-15)';
COMMENT ON COLUMN producto.altura_cm IS 'Altura del tejido en centimetros (DD-16)';
COMMENT ON COLUMN producto.abertura IS 'Pulgadas en el hexagonal, centimetros en el resto (DD-16)';
COMMENT ON COLUMN producto.precio_venta IS 'Precio de una unidad de unidad_venta (DD-13)';
COMMENT ON COLUMN producto.precio_metro IS 'Precio del metro cortado, cargado del listado (DD-13, RN-17)';
COMMENT ON COLUMN producto.costo IS 'Ultimo costo registrado, editable a mano (DD-05). Se copia a la linea del pedido al confirmar (RN-34)';


--------------------------------------------------------------------------------
-- 3. STOCK
--    Piezas CERRADAS por producto: rollos sin abrir, kilos o unidades.
--    Son intercambiables entre si, por eso van como contador (DD-02).
--------------------------------------------------------------------------------
CREATE TABLE stock (
    id_producto         INTEGER      NOT NULL,
    cantidad_cerrada    INTEGER      DEFAULT 0 NOT NULL,
    fecha_actualizacion TIMESTAMP(0) DEFAULT LOCALTIMESTAMP(0) NOT NULL,
    CONSTRAINT pk_stock          PRIMARY KEY (id_producto),
    CONSTRAINT fk_stock_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto),
    CONSTRAINT ck_stock_cantidad CHECK (cantidad_cerrada >= 0)
);

COMMENT ON COLUMN stock.cantidad_cerrada IS 'Piezas enteras disponibles: rollos sin abrir, kilos o unidades (DD-02)';


--------------------------------------------------------------------------------
-- 4. ROLLO_ABIERTO
--    Una fila SOLO por rollo ya empezado (DD-02).
--------------------------------------------------------------------------------
CREATE TABLE rollo_abierto (
    id_rollo          INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    id_producto       INTEGER       NOT NULL,
    metros_iniciales  NUMERIC(7,2)  NOT NULL,
    metros_restantes  NUMERIC(7,2)  NOT NULL,
    fecha_apertura    TIMESTAMP(0)  DEFAULT LOCALTIMESTAMP(0) NOT NULL,
    estado            VARCHAR(10)   DEFAULT 'ABIERTO' NOT NULL,
    CONSTRAINT pk_rollo_abierto   PRIMARY KEY (id_rollo),
    CONSTRAINT fk_rollo_producto  FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto),
    CONSTRAINT ck_rollo_estado    CHECK (estado IN ('ABIERTO','AGOTADO')),
    CONSTRAINT ck_rollo_restantes CHECK (metros_restantes >= 0),
    CONSTRAINT ck_rollo_coherente CHECK (metros_restantes <= metros_iniciales)
);

-- Sostiene la busqueda del rollo a cortar: por producto, abiertos,
-- ordenados por metros restantes (RN-09 con el criterio del menor que alcanza).
CREATE INDEX ix_rollo_corte ON rollo_abierto (id_producto, estado, metros_restantes);

COMMENT ON TABLE  rollo_abierto IS 'Un registro por rollo empezado, con sus metros restantes (DD-02)';
COMMENT ON COLUMN rollo_abierto.estado IS 'Pasa a AGOTADO cuando metros_restantes llega a 0 (RN-11)';


--------------------------------------------------------------------------------
-- 5. CLIENTE
--    Solo el nombre es obligatorio (DD-10).
--------------------------------------------------------------------------------
CREATE TABLE cliente (
    id_cliente         INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    nombre             VARCHAR(120)  NOT NULL,
    documento          VARCHAR(20)   NULL,
    telefono           VARCHAR(30)   NULL,
    direccion_entrega  VARCHAR(200)  NULL,
    activo             CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_cliente        PRIMARY KEY (id_cliente),
    CONSTRAINT ck_cliente_activo CHECK (activo IN ('S','N'))
);

CREATE INDEX ix_cliente_nombre ON cliente (UPPER(nombre));


--------------------------------------------------------------------------------
-- 6. PEDIDO
--    Estados: BORRADOR, CONFIRMADO, ENTREGADO, COBRADO, ANULADO (DD-06).
--------------------------------------------------------------------------------
CREATE TABLE pedido (
    id_pedido           INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    id_cliente          INTEGER       NOT NULL,
    fecha_pedido        TIMESTAMP(0)  DEFAULT LOCALTIMESTAMP(0) NOT NULL,
    estado              VARCHAR(12)   DEFAULT 'BORRADOR' NOT NULL,
    monto_flete         BIGINT        DEFAULT 0 NOT NULL,
    subtotal            BIGINT        DEFAULT 0 NOT NULL,
    total               BIGINT        DEFAULT 0 NOT NULL,
    fecha_confirmacion  TIMESTAMP(0)  NULL,
    fecha_entrega       TIMESTAMP(0)  NULL,
    fecha_cobro         TIMESTAMP(0)  NULL,
    observacion         VARCHAR(400)  NULL,
    CONSTRAINT pk_pedido         PRIMARY KEY (id_pedido),
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente),
    CONSTRAINT ck_pedido_estado  CHECK (estado IN
        ('BORRADOR','CONFIRMADO','ENTREGADO','COBRADO','ANULADO')),
    CONSTRAINT ck_pedido_flete   CHECK (monto_flete >= 0),
    CONSTRAINT ck_pedido_total   CHECK (total >= 0)
);

CREATE INDEX ix_pedido_estado  ON pedido (estado, fecha_pedido);
CREATE INDEX ix_pedido_cliente ON pedido (id_cliente);
-- El reporte del mes agrupa los cobrados por su fecha de cobro (SP-07)
CREATE INDEX ix_pedido_cobro   ON pedido (fecha_cobro);

COMMENT ON COLUMN pedido.estado IS 'BORRADOR, CONFIRMADO, ENTREGADO, COBRADO o ANULADO (DD-06)';
COMMENT ON COLUMN pedido.monto_flete IS 'Monto escrito a mano, sin descuento (DD-12, RN-25)';


--------------------------------------------------------------------------------
-- 7. PEDIDO_DETALLE
--    Una fila por linea. El precio Y el costo se copian al confirmar:
--    un cambio posterior en el producto no altera pedidos ya cerrados
--    (RN-19 para el precio, RN-34 para el costo).
--------------------------------------------------------------------------------
CREATE TABLE pedido_detalle (
    id_pedido        INTEGER       NOT NULL,
    nro_linea        INTEGER       NOT NULL,
    id_producto      INTEGER       NOT NULL,
    tipo_venta       VARCHAR(10)   NOT NULL,
    cantidad         NUMERIC(10,2) NOT NULL,
    precio_unitario  BIGINT        NOT NULL,
    descuento_pct    NUMERIC(5,2)  DEFAULT 0 NOT NULL,
    subtotal         BIGINT        NOT NULL,
    costo_unitario   BIGINT        NULL,
    id_rollo         INTEGER       NULL,
    CONSTRAINT pk_pedido_detalle    PRIMARY KEY (id_pedido, nro_linea),
    CONSTRAINT fk_detalle_pedido    FOREIGN KEY (id_pedido)
        REFERENCES pedido (id_pedido) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_producto  FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto),
    CONSTRAINT fk_detalle_rollo     FOREIGN KEY (id_rollo)
        REFERENCES rollo_abierto (id_rollo),
    CONSTRAINT ck_detalle_tipo      CHECK (tipo_venta IN ('ROLLO','METRO','KILO','UNIDAD')),
    CONSTRAINT ck_detalle_cantidad  CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_descuento CHECK (descuento_pct BETWEEN 0 AND 100),
    CONSTRAINT ck_detalle_nro       CHECK (nro_linea > 0)
);

CREATE INDEX ix_detalle_producto ON pedido_detalle (id_producto);

COMMENT ON COLUMN pedido_detalle.precio_unitario IS 'Precio copiado del producto al confirmar (RN-19)';
COMMENT ON COLUMN pedido_detalle.costo_unitario IS 'Costo copiado al confirmar. En venta por metro: costo del producto / metraje_rollo (RN-33, RN-34)';
COMMENT ON COLUMN pedido_detalle.id_rollo IS 'Rollo del que se corto, cuando tipo_venta = METRO (RN-15)';


