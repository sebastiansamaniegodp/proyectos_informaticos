--------------------------------------------------------------------------------
-- 10. VISTA DE STOCK DISPONIBLE
--     Resuelve la cuenta del DD-02 en un solo lugar (RN-07).
--------------------------------------------------------------------------------
CREATE VIEW vw_stock_disponible AS
SELECT p.id_producto,
       p.codigo,
       p.descripcion,
       p.unidad_venta,
       p.fraccionable,
       COALESCE(s.cantidad_cerrada, 0)                 AS piezas_cerradas,
       COALESCE(ra.rollos_abiertos, 0)                 AS rollos_abiertos,
       COALESCE(ra.metros_sueltos, 0)                  AS metros_sueltos,
       CASE
           WHEN p.fraccionable = 'S'
           THEN COALESCE(s.cantidad_cerrada, 0) * COALESCE(p.metraje_rollo, 0)
                + COALESCE(ra.metros_sueltos, 0)
           ELSE COALESCE(s.cantidad_cerrada, 0)
       END                                             AS disponible_total
  FROM producto p
  LEFT JOIN stock s
         ON s.id_producto = p.id_producto
  LEFT JOIN (SELECT id_producto,
                    COUNT(*)              AS rollos_abiertos,
                    SUM(metros_restantes) AS metros_sueltos
               FROM rollo_abierto
              WHERE estado = 'ABIERTO'
              GROUP BY id_producto) ra
         ON ra.id_producto = p.id_producto
 WHERE p.activo = 'S';

COMMENT ON VIEW vw_stock_disponible IS 'Piezas cerradas, rollos abiertos y disponible total por producto (DD-02, RN-07)';


