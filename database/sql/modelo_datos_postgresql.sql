-- 8. MOVIMIENTO_STOCK
--    Toda entrada y salida de mercaderia. cantidad lleva signo:
--    positiva ingresa, negativa sale (DD-07).
--------------------------------------------------------------------------------
CREATE TABLE movimiento_stock (
    id_movimiento  INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    id_producto    INTEGER       NOT NULL,
    id_rollo       INTEGER       NULL,
    id_pedido      INTEGER       NULL,
    tipo           VARCHAR(12)   NOT NULL,
    motivo         VARCHAR(15)   NULL,
    cantidad       NUMERIC(10,2) NOT NULL,
    unidad         VARCHAR(10)   NOT NULL,
    fecha          TIMESTAMP(0)  DEFAULT LOCALTIMESTAMP(0) NOT NULL,
    observacion    VARCHAR(200)  NULL,
    CONSTRAINT pk_movimiento   PRIMARY KEY (id_movimiento),
    CONSTRAINT fk_mov_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto),
    CONSTRAINT fk_mov_rollo    FOREIGN KEY (id_rollo)
        REFERENCES rollo_abierto (id_rollo),
    CONSTRAINT fk_mov_pedido   FOREIGN KEY (id_pedido)
        REFERENCES pedido (id_pedido),
    CONSTRAINT ck_mov_tipo     CHECK (tipo IN ('INGRESO','VENTA','AJUSTE','ANULACION')),
    CONSTRAINT ck_mov_unidad   CHECK (unidad IN ('ROLLO','METRO','KILO','UNIDAD')),
    CONSTRAINT ck_mov_cantidad CHECK (cantidad <> 0),
    -- CORREGIDA EN LA v1.1. La version anterior omitia IS NOT NULL y dejaba
    -- guardar un ajuste sin motivo: con motivo nulo la primera rama daba
    -- DESCONOCIDO, no FALSO, y el CHECK solo rechaza con FALSO (RN-30).
    CONSTRAINT ck_mov_motivo CHECK (
        (tipo = 'AJUSTE'  AND motivo IS NOT NULL
                          AND motivo IN ('ROTURA','MUESTRA','OBSEQUIO','INVENTARIO'))
     OR (tipo = 'INGRESO' AND motivo IS NOT NULL
                          AND motivo IN ('CARGA_INICIAL','REPOSICION'))
     OR (tipo IN ('VENTA','ANULACION') AND motivo IS NULL)
    ),
    -- Un ingreso siempre suma y una venta siempre resta (RN-35)
    CONSTRAINT ck_mov_signo CHECK (
        (tipo = 'INGRESO' AND cantidad > 0)
     OR (tipo = 'VENTA'   AND cantidad < 0)
     OR (tipo IN ('AJUSTE','ANULACION'))
    )
);

CREATE INDEX ix_mov_producto ON movimiento_stock (id_producto, fecha);
CREATE INDEX ix_mov_pedido   ON movimiento_stock (id_pedido);

COMMENT ON TABLE  movimiento_stock IS 'Trazabilidad de toda entrada y salida de mercaderia (DD-07, RN-15)';
COMMENT ON COLUMN movimiento_stock.cantidad IS 'Con signo: positiva ingresa, negativa sale';
COMMENT ON COLUMN movimiento_stock.motivo IS 'AJUSTE: rotura, muestra, obsequio o inventario (RN-30). INGRESO: carga inicial o reposicion (RN-35)';


